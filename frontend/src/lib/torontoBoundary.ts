/**
 * Ray casting: counts how many boundary edges a ray from the point crosses.
 * Odd means inside. Cheap enough to run per grid cell, and the caller's bbox
 * intersection rejects most points before this is reached.
 */
export function insideToronto(lng: number, lat: number): boolean {
  let inside = false
  for (let i = 0, j = TORONTO_BOUNDARY.length - 1; i < TORONTO_BOUNDARY.length; j = i++) {
    const [xi, yi] = TORONTO_BOUNDARY[i]
    const [xj, yj] = TORONTO_BOUNDARY[j]
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside
    }
  }
  return inside
}
